// Codeforces Round 1125 (Div. 3)
// https://codeforces.com/contest/2275/problem/A
// A. In Search of Convenience

#include <bits/stdc++.h>
using namespace std;

int main()
{
    int t;
    cin >> t;
    while (t--)
    {
        int x0, y0, R;
        cin >> x0 >> y0 >> R;

        cout << x0 << " " << R + y0 << endl;
    }
}
